## Mapa do tópico — o que cai e por quê

Formação territorial é o tópico que dá base histórica e estrutural para todo o resto de Geopolítica — entender como o território brasileiro se organizou administrativamente (regiões, unidades federativas) é pré-requisito para os tópicos seguintes sobre fronteiras e logística.

## Teoria essencial

O território brasileiro tem extensão continental (o quinto maior país do mundo em área), organizado politicamente em **26 Estados** e o **Distrito Federal**, totalizando **27 unidades federativas**, e mais de 5.500 Municípios. A divisão em **cinco grandes regiões** (Norte, Nordeste, Centro-Oeste, Sudeste, Sul), adotada pelo IBGE, é uma **regionalização oficial** para fins estatísticos e de planejamento, baseada principalmente em critérios de contiguidade territorial e características socioeconômicas — não se confunde com outras propostas de regionalização (como a divisão geoeconômica em Amazônia, Centro-Sul e Nordeste, de uso mais analítico e menos oficial-administrativo).

A formação territorial brasileira teve como marco inicial o **Tratado de Tordesilhas** (1494), que dividia as terras recém-descobertas entre Portugal e Espanha, sendo sucessivamente ultrapassado pela expansão portuguesa para o interior (movimento das **bandeiras**, em busca de metais preciosos e captura de indígenas), consolidando fronteiras muito além da linha original do tratado — esse processo de expansão para o oeste é um dos fatores históricos centrais da atual configuração territorial brasileira, posteriormente formalizado por tratados diplomáticos específicos com os países vizinhos.

O **Barão do Rio Branco** é a figura histórica mais associada à consolidação diplomática das fronteiras brasileiras no início do século XX, tendo resolvido, por via negocial (sem recorrer à guerra), diversas disputas territoriais com países vizinhos, como a incorporação do **Acre** (adquirido da Bolívia pelo Tratado de Petrópolis, de 1903, mediante compensação financeira e territorial), consolidando grande parte do desenho atual das fronteiras terrestres do país.

A **Região Norte** é a maior em extensão territorial, mas com menor densidade demográfica relativa; a **Região Sudeste**, embora menor em área, concentra a maior parcela da população e do PIB nacional — assimetrias regionais que fundamentam boa parte das políticas públicas de desenvolvimento regional e da própria distribuição da infraestrutura de transportes no país.

