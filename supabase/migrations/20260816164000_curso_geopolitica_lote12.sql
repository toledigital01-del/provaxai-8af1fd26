## Teoria essencial

A **matriz energética brasileira** tem uma característica que a diferencia da maior parte do mundo: é predominantemente baseada em fontes **renováveis**, especialmente a energia **hidrelétrica**, historicamente a principal fonte de geração de eletricidade no país, favorecida pela vasta rede hidrográfica nacional. Nas últimas décadas, houve diversificação com crescimento expressivo de fontes como **eólica**, **solar** e **biomassa** (esta última impulsionada pela produção de etanol a partir da cana-de-açúcar), consolidando uma matriz elétrica com participação renovável significativamente superior à média mundial.

