## Teoria essencial

O Brasil possui fronteiras terrestres com **dez países** sul-americanos, sendo o único país da América do Sul que não faz fronteira apenas com **Chile e Equador**: Uruguai, Argentina, Paraguai, Bolívia, Peru, Colômbia, Venezuela, Guiana, Suriname e Guiana Francesa (território ultramarino francês, não um país soberano independente, mas tratado como fronteira internacional para fins de controle territorial).

A **faixa de fronteira** é definida constitucionalmente (art. 20, §2º, da Constituição Federal) como a faixa de até **150 km de largura**, ao longo das fronteiras terrestres, considerada **fundamental para a defesa do território nacional**, tendo sua ocupação e utilização reguladas em lei específica (Lei nº 6.634/1979 e regulamentação posterior). Nessa faixa, determinadas atividades sofrem restrições ou exigem autorização especial, como a alienação de terras a estrangeiros, construção de obras que possam interferir no tráfego aéreo, e a instalação de determinadas empresas ou atividades consideradas estratégicas do ponto de vista da segurança nacional.

A extensão total das fronteiras terrestres brasileiras é de aproximadamente **16.800 km** — a maior extensão de fronteira terrestre entre países da América do Sul —, o que torna o controle e a fiscalização dessa extensa faixa um desafio logístico e de segurança pública significativo, envolvendo diretamente órgãos como a Polícia Federal (principal responsável pelo controle migratório e de fronteiras) e a PRF, no patrulhamento das rodovias federais que dão acesso a essas regiões.

