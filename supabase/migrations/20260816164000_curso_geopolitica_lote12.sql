## Mapa do tópico — o que cai e por quê

Esse é, sem dúvida, o tópico mais diretamente ligado ao seu futuro trabalho — a estrutura da malha rodoviária federal é literalmente o "chão" onde a PRF atua. A prova testa a nomenclatura das rodovias, a predominância do transporte rodoviário na matriz brasileira e seus impactos.

## Teoria essencial

A **matriz de transportes brasileira** é historicamente **predominantemente rodoviária**, ao contrário de países de dimensão territorial semelhante (como Estados Unidos, China ou Rússia), que têm matriz mais equilibrada ou com maior participação ferroviária e hidroviária — essa característica é resultado de opções de política de infraestrutura consolidadas especialmente a partir de meados do século XX, e gera consequências relevantes como maior custo logístico, maior consumo de combustíveis fósseis e maior sinistralidade viária, se comparado a matrizes de transporte mais diversificadas.

A **nomenclatura das rodovias federais** segue um sistema de codificação: rodovias com prefixo **BR** são federais. O primeiro número (ou dígito) da codificação indica a orientação predominante: rodovias **radiais** (numeração iniciada em 0, partindo de Brasília em direção às fronteiras ou ao litoral), **longitudinais** (numeração iniciada em 1, com orientação predominantemente **norte-sul**), **transversais** (numeração iniciada em 2, orientação predominantemente **leste-oeste**), **diagonais** (numeração iniciada em 3, orientação diagonal) e **rodovias de ligação** (numeração iniciada em 4, conectando outras rodovias sem seguir orientação específica preponderante).

Exemplos frequentemente cobrados: a **BR-101**, uma das mais extensas do país, é rodovia **longitudinal**, percorrendo praticamente todo o litoral brasileiro, de norte a sul; a **BR-116**, também longitudinal, é uma das principais rotas de ligação entre o Sul/Sudeste e o Nordeste do país; a **BR-364**, rodovia radial que conecta Brasília ao extremo oeste do país (Acre/Rondônia).

A predominância rodoviária gera desafios de **segurança viária** significativos, com o Brasil registrando historicamente índices elevados de acidentes e mortes no trânsito em comparação a países com matriz de transporte mais diversificada — dado que fundamenta parte relevante da própria justificativa institucional da atuação da PRF, cuja missão constitucional de patrulhamento ostensivo das rodovias federais é diretamente relacionada à necessidade de reduzir a sinistralidade nessa extensa e predominante malha rodoviária.

