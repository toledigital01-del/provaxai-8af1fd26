## Mapa do tópico — o que cai e por quê

A prova de espanhol da Cebraspe segue a mesma lógica da prova de português: um texto-base e itens de certo/errado sobre o que ele afirma. A armadilha mais específica do espanhol, porém, é lexical — palavras parecidas com o português que têm sentido **diferente** (os falsos cognatos/heterossemânticos), responsáveis pela maioria dos erros de quem "acha que entende espanhol só porque é parecido com português".

## Teoria essencial

A proximidade entre português e espanhol é ao mesmo tempo vantagem e armadilha: muitas palavras são **cognatas** (semelhantes na forma e no sentido, facilitando a compreensão), mas outras são **heterossemânticas** ou **falsos cognatos** (semelhantes na forma, mas com sentido **diferente** entre os dois idiomas) — é justamente aí que a prova concentra a maior parte das pegadinhas de vocabulário.

Os falsos cognatos mais cobrados: **"embarazada"** não significa "envergonhada", significa **grávida**; **"exquisito"** não significa "esquisito", significa **saboroso/refinado**; **"apellido"** não significa "apelido", significa **sobrenome**; **"borracha"** não significa o material "borracha", significa **bêbada**; **"oficina"** não significa "escritório", significa **oficina mecânica**; **"escritorio"** é que significa **escritório/mesa de trabalho**; **"largo"** não significa "largo" (de largura), significa **longo/comprido**; **"vaso"** não significa "vaso" de planta, significa **copo**; **"taza"** significa **xícara**; **"rojo"** significa **vermelho** (não "roxo", que em espanhol é "morado" ou "violeta"); **"pelo"** significa **cabelo**; **"sitio"** significa **lugar**; **"todavía"** significa **ainda** (não "todavia" no sentido português de "porém", que em espanhol é "sin embargo").

