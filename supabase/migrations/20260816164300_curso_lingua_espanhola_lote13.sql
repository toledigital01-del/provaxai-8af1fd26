## Mapa do tópico — o que cai e por quê

Verbos são a estrutura gramatical mais testada em textos de espanhol para concurso — o Modo Subjuntivo, em especial, gera dificuldade porque seu uso em espanhol é mais frequente e mais sistemático do que o equivalente em português, exigindo atenção redobrada do candidato.

## Teoria essencial

O **Modo Indicativo** expressa fatos considerados certos, reais ou objetivos pelo falante — usado para afirmações diretas sobre presente, passado e futuro. O **Presente de Indicativo** tem formação regular com terminações próprias para cada conjugação (-ar, -er, -ir), com diversos verbos irregulares frequentemente cobrados (como "ser", "estar", "tener", "ir").

O **Pretérito Perfecto Simple** (equivalente ao pretérito perfeito simples do português: "hablé", "comí") expressa ação concluída num momento específico e delimitado do passado. O **Pretérito Imperfecto** (equivalente ao pretérito imperfeito: "hablaba", "comía") expressa ação habitual, contínua ou em desenvolvimento no passado, sem marcar seu término. O **Pretérito Perfecto Compuesto** (equivalente ao pretérito perfeito composto: "he hablado") expressa ação passada com conexão relevante ao presente.

O **Modo Subjuntivo** expressa dúvida, desejo, emoção, possibilidade, ordem indireta ou hipótese — situações **não** apresentadas como fato certo pelo falante. É empregado sistematicamente após determinadas expressões e estruturas: verbos de **desejo** ("querer que", "esperar que"), de **dúvida ou negação** ("dudar que", "no creer que"), de **emoção** ("alegrarse de que", "temer que"), estruturas **impessoais de opinião/valoração** ("es importante que", "es necesario que"), orações **finais** ("para que"), e orações **condicionais** de caráter hipotético ou irreal. Um erro comum de quem aprende espanhol vindo do português é usar o indicativo nessas estruturas, seguindo o hábito mais frouxo do português brasileiro coloquial, quando a norma do espanhol exige categoricamente o subjuntivo.

As **perífrasis verbales** (locuções verbais) são construções formadas por um verbo auxiliar (conjugado) mais um verbo principal (no infinitivo, gerúndio ou particípio), expressando um matiz de significado que o verbo simples não expressaria sozinho. As mais cobradas: **"ir a" + infinitivo** (futuro próximo/intenção, equivalente a "ir + infinitivo" em português: "voy a estudiar"), **"estar" + gerúndio** (ação em desenvolvimento, equivalente ao gerúndio português: "estoy estudiando"), **"acabar de" + infinitivo** (ação recém-concluída, equivalente a "acabar de" em português: "acabo de llegar") e **"tener que" / "haber que" + infinitivo** (obrigação: "tengo que ir", "hay que estudiar").

## Como a Cebraspe cobra este assunto

O item costuma apresentar uma frase que exigiria subjuntivo (por conter estrutura de dúvida, desejo ou valoração) e testar se o candidato reconhece a forma correta, ou testa o significado específico de uma perífrase verbal em contexto.

## Pegadinhas e palavras-armadilha

- Expressões de dúvida, desejo, emoção e valoração impessoal ("es importante que", "espero que", "dudo que") **exigem** subjuntivo em espanhol, de forma mais sistemática do que em português.
- "Ir a" + infinitivo: futuro próximo/intenção. "Estar" + gerúndio: ação em desenvolvimento. "Acabar de" + infinitivo: ação recém-concluída.
