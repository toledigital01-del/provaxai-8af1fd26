## Mapa do tópico — o que cai e por quê

Conectores organizam a lógica argumentativa de um texto, e a prova de espanhol testa se o candidato reconhece corretamente o valor semântico de cada um (causa, consequência, oposição, condição), da mesma forma que testaria em português — a diferença é puramente lexical, mas gera confusão pela semelhança parcial com termos portugueses.

## Teoria essencial

Os conectores **aditivos** somam ideias de mesmo sentido: **"y"** (e), **"además"** (além disso), **"también"** (também), **"asimismo"** (da mesma forma). Os conectores **adversativos/opositivos** marcam contraste: **"pero"** (mas), **"sin embargo"** (porém/no entanto — não confundir com "todavía", que significa "ainda"), **"no obstante"** (não obstante), **"aunque"** (embora/ainda que).

Os conectores **causais** introduzem a razão de um fato: **"porque"** (porque), **"ya que"** (já que), **"puesto que"** (visto que), **"debido a"** (devido a). Os **consecutivos** introduzem o resultado/consequência: **"por lo tanto"** (portanto), **"así que"** (então/de modo que), **"en consecuencia"** (em consequência), **"por eso"** (por isso).

Os conectores **condicionais** introduzem uma hipótese: **"si"** (se), **"a menos que"** (a menos que, geralmente seguido de subjuntivo), **"con tal de que"** (contanto que, seguido de subjuntivo). Os **finais** introduzem propósito/objetivo: **"para"** (para), **"para que"** (para que, seguido de subjuntivo), **"a fin de que"** (a fim de que).

Um falso cognato particularmente traiçoeiro dentro deste tópico é justamente **"sin embargo"**: apesar de "embargo" lembrar "embargar" em português (no sentido jurídico), a expressão completa significa **"porém/no entanto"**, um conector puramente **adversativo**, sem qualquer relação com o sentido jurídico de embargo em português. Da mesma forma, **"pero"** não tem relação com "perô" ou qualquer outro termo parecido do português — significa simplesmente **"mas"**.

A identificação correta do conector dentro de um texto é fundamental para a interpretação: trocar mentalmente um conector adversativo por um causal (ou vice-versa) inverte completamente a lógica argumentativa que o autor pretendia construir — por isso a prova frequentemente testa a compreensão do texto justamente através da correta identificação do papel lógico exercido por um conector específico.

## Como a Cebraspe cobra este assunto

O item costuma pedir que o candidato identifique o valor semântico correto (causal, consecutivo, adversativo, condicional) de um conector destacado no texto-base, ou testa diretamente a tradução/sentido de "sin embargo" (porém), frequentemente confundido pela semelhança com "embargo" em português.

## Pegadinhas e palavras-armadilha

- **Sin embargo** = porém/no entanto (adversativo) — não tem relação com o sentido jurídico de "embargo" em português.
- **Pero** = mas (adversativo simples).
- **Ya que / puesto que** = já que/visto que (causais).
- **Por lo tanto / así que** = portanto/então (consecutivos).
- Conectores condicionais e finais (a menos que, para que, con tal de que) frequentemente exigem **subjuntivo** na oração que introduzem.

