## Mapa do tópico — o que cai e por quê

Além dos falsos cognatos (heterossemânticos), a prova explora outras duas categorias de "palavras parecidas mas diferentes": os heterogenéricos (mesmo sentido, gênero gramatical diferente) e os heterotônicos (mesma grafia/sentido parecido, sílaba tônica diferente) — categorias menos conhecidas, mas igualmente cobráveis.

## Teoria essencial

Os **heterogenéricos** são palavras com sentido equivalente em português e espanhol, mas que mudam de **gênero gramatical** entre os dois idiomas — o que afeta a concordância de artigos e adjetivos. Exemplos clássicos: **"la leche"** (o leite, feminino em espanhol, masculino em português), **"la sangre"** (o sangue, feminino em espanhol), **"la nariz"** (o nariz, feminino em espanhol), **"la miel"** (o mel, feminino em espanhol), **"el equipaje"** (a bagagem, masculino em espanhol, feminino em português), **"el viaje"** (a viagem, masculino em espanhol), **"el árbol"** (a árvore, masculino em espanhol), **"el puente"** (a ponte, masculino em espanhol), **"el color"** (a cor, masculino em espanhol) e **"el origen"** (a origem, masculino em espanhol).

Os **heterotônicos** são palavras com grafia igual ou muito semelhante entre os dois idiomas, mas com a sílaba tônica (a sílaba mais forte na pronúncia) diferente — em português-espanhol, o padrão mais recorrente é palavras que são paroxítonas em português e se tornam oxítonas em espanhol (ou vice-versa), afetando inclusive a acentuação gráfica. Exemplos: **"régimen"** (regime, com acentuação diferente do português), **"académico"**, **"país"** (com til no i, diferente de "país" em português).

O sistema de **acentuação gráfica** do espanhol segue regras próprias, distintas do português: palavras **agudas** (equivalente às oxítonas) são acentuadas quando terminam em vogal, N ou S; palavras **graves ou llanas** (equivalente às paroxítonas) são acentuadas quando **não** terminam em vogal, N ou S — regra praticamente **invertida** em relação ao português, o que costuma confundir o candidato que aplica a lógica portuguesa diretamente ao espanhol; palavras **esdrújulas** (equivalente às proparoxítonas) são **sempre** acentuadas, assim como em português.

O uso de **artigos** também exige atenção: diante de substantivo feminino singular iniciado por "a" ou "ha" tônico, o espanhol usa o artigo masculino "el" por questão de eufonia (como em "el agua", embora o substantivo continue sendo gramaticalmente feminino, concordando no plural como "las aguas") — regra semelhante, mas não idêntica, à do português.

## Como a Cebraspe cobra este assunto

