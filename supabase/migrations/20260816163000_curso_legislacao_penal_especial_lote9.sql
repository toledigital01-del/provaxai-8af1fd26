## Mapa do tópico — o que cai e por quê

A Lei de Abuso de Autoridade é extremamente relevante pra você, porque tipifica exatamente os limites da sua futura atuação como agente público com poder de polícia — a prova testa tanto o elemento subjetivo específico exigido pela lei (que a torna diferente de mero erro procedimental) quanto as condutas específicas mais relacionadas à atividade policial, como prisão e busca.

## Teoria essencial

A Lei nº 13.869/2019 exige, para a configuração de qualquer dos crimes nela previstos, o elemento subjetivo específico consistente na **finalidade específica de prejudicar outrem, ou beneficiar a si mesmo ou a terceiro, ou, ainda, por mero capricho ou satisfação pessoal** (art. 1º, §1º) — sem esse dolo específico, a conduta do agente pode até configurar erro, falha procedimental ou outra infração, mas **não configura abuso de autoridade**. Esse é o ponto mais cobrado da lei inteira: divergência de interpretação jurídica ou de valoração de fatos e provas, conduzida de forma fundamentada, **não configura abuso de autoridade** (art. 1º, §2º).

Entre as condutas típicas mais relacionadas à atividade policial: decretar ou executar **condução coercitiva** de testemunha ou investigado, sem prévia intimação para comparecimento voluntário (art. 10); manter presa a pessoa **além do prazo legal**, sem promover a soltura ou a comunicação à autoridade judicial (art. 9º); constranger o preso ou detento, mediante violência, grave ameaça ou redução de sua capacidade de resistência, a **exibir-se ou submeter-se a situação vexatória** (art. 13); prolongar a execução de **busca domiciliar**, mediante o uso de força, ameaça ou grave abuso, além do tempo necessário à sua realização, ou além do dia estabelecido, para causar constrangimento ilegal (art. 22, incisos I a III); e proceder à **filmagem ou fotografia** de pessoa presa ou de investigado, sem autorização, em situação que exponha o preso a vexame ou constrangimento (art. 13, parágrafo único).

Também tipificam abuso de autoridade: submeter o preso a interrogatório policial durante o período de repouso noturno, ressalvadas as hipóteses de flagrante ou consentimento (art. 18); deixar de identificar-se, ou identificar-se de forma falsa, ao realizar prisão ou qualquer medida de restrição de liberdade (art. 15); e decretar, de forma indevida, medida de restrição de direito sem observar as formalidades legais.

As penas previstas são, em regra, de **detenção**, cumuláveis com **multa** e com efeitos de condenação que podem incluir **inabilitação para função ou cargo público** por período determinado, quando a condenação decorrer de abuso cometido no exercício de função pública.

