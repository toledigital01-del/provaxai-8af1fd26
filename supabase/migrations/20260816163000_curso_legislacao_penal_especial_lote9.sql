## Mapa do tópico — o que cai e por quê

A Lei Maria da Penha tem grande relevância prática pra atuação policial — a prova testa principalmente as formas de violência doméstica reconhecidas pela lei e as medidas protetivas de urgência que podem ser aplicadas, instrumentos que o próprio policial frequentemente aciona no atendimento de ocorrências.

## Teoria essencial

A Lei nº 11.340/2006 (Lei Maria da Penha) configura violência doméstica e familiar contra a mulher quando praticada no âmbito da **unidade doméstica**, da **família** (incluindo pessoas unidas por laços naturais, por afinidade ou por vontade expressa) ou em **relação íntima de afeto**, na qual o agressor conviva ou tenha convivido com a ofendida, independentemente de coabitação — importante notar que a lei **não exige** que agressor e vítima morem juntos no momento do fato, nem que sejam ou tenham sido casados, bastando a relação íntima de afeto caracterizada.

A lei reconhece **cinco formas de violência doméstica** (art. 7º): **física** (que ofenda a integridade ou saúde corporal), **psicológica** (que cause dano emocional e diminuição da autoestima, ou que vise degradar/controlar ações, comportamentos, crenças e decisões, mediante ameaça, humilhação, manipulação, isolamento, entre outras condutas), **sexual** (que constranja a presenciar, manter ou participar de relação sexual não desejada, mediante intimidação, ameaça, coação ou uso da força), **patrimonial** (que configure retenção, subtração, destruição parcial ou total de objetos, instrumentos de trabalho, documentos pessoais, bens, valores e direitos ou recursos econômicos) e **moral** (que configure calúnia, difamação ou injúria).

As **medidas protetivas de urgência** se dividem em: as que **obrigam o agressor** (art. 22 — como suspensão da posse ou restrição do porte de armas, afastamento do lar/domicílio, proibição de aproximação da ofendida/familiares/testemunhas com fixação de distância mínima, proibição de contato por qualquer meio de comunicação, restrição ou suspensão de visitas aos dependentes menores, prestação de alimentos) e as que **protegem a ofendida** (art. 23 — encaminhamento a programa de proteção, recondução ao domicílio após afastamento do agressor, afastamento do lar sem prejuízo de direitos, separação de corpos).

A **feminicídio** e a **lesão corporal qualificada por violência doméstica** (aumento de pena do art. 129, §9º e §11 do Código Penal) são reflexos penais diretos da caracterização de violência doméstica prevista na Lei Maria da Penha. Um ponto de destaque jurisprudencial: o STF já reconheceu a constitucionalidade da lei mesmo diante de eventual questionamento sobre tratamento diferenciado por gênero, considerando a proteção legítima e proporcional diante de contexto histórico de vulnerabilidade da mulher em relações domésticas.

## Como a Cebraspe cobra este assunto

O item costuma descrever uma situação de violência doméstica e pedir a classificação correta da forma de violência (física, psicológica, patrimonial, moral, sexual), ou testa se o candidato sabe que a lei não exige coabitação atual entre agressor e vítima para sua aplicação.

## Pegadinhas e palavras-armadilha

- A lei **não exige coabitação atual** entre agressor e vítima — basta relação íntima de afeto, ainda que não haja mais convivência.
