## Mapa do tópico — o que cai e por quê

Estatuto do Desarmamento é outro tópico de aplicação prática direta pra você — a distinção entre posse (dentro de casa/local de trabalho) e porte (fora, em via pública), e entre arma de uso permitido e restrito, são a espinha dorsal do que a prova cobra.

## Teoria essencial

A **posse irregular de arma de fogo de uso permitido** (art. 12 da Lei nº 10.826/2003) tipifica manter sob guarda arma de fogo, acessório ou munição, de uso permitido, em desacordo com determinação legal ou regulamentar, **no interior de residência ou dependência desta, ou no local de trabalho** — pena de detenção, a infração menos grave do estatuto.

O **porte ilegal de arma de fogo de uso permitido** (art. 14) é portar, deter, adquirir, fornecer, receber, ter em depósito, transportar, ceder (ainda que gratuitamente), emprestar, remeter, empregar, manter sob guarda ou ocultar arma de fogo, acessório ou munição, de uso permitido, **sem autorização e em desacordo com determinação legal ou regulamentar**, **fora de casa ou do local de trabalho** — pena de reclusão, mais grave que a posse, por representar risco maior à coletividade ao circular pela via pública.

A **posse ou porte de arma de fogo de uso restrito** (art. 16) — armas de maior potencial ofensivo, cujo uso é reservado a categorias específicas (Forças Armadas, forças de segurança em certas hipóteses) — é crime ainda mais grave, com pena de reclusão mais elevada que as anteriores, e o mesmo artigo prevê **causas de aumento** quando a arma tiver numeração, marca ou qualquer sinal de identificação raspado, suprimido ou adulterado, ou quando o agente for policial, ainda que aposentado, ou integrante das Forças Armadas.

Um ponto de destaque: o estatuto prevê a **abolitio criminis temporária** (art. 30 e disposições transitórias, com prorrogações sucessivas por leis posteriores) para quem possuía arma de fogo de uso permitido em desacordo com a lei e a entregasse à Polícia Federal dentro do prazo fixado, mediante recibo, ficando isento de responsabilidade penal e do pagamento de taxas — mecanismo já utilizado em campanhas de entrega voluntária de armas.

O **Certificado de Registro** e a **autorização de porte** são exigências administrativas distintas: o registro da arma (no Sinarm ou Sigma, conforme o caso) legaliza a posse; a autorização de porte, mais restrita e concedida em hipóteses específicas (como comprovada necessidade em razão de atividade profissional de risco), legaliza o transporte da arma municiada, fora de casa, em via pública.

