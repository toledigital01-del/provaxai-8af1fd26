## Mapa do tópico — o que cai e por quê

Lei de Drogas é altamente relevante pra você, futuro policial rodoviário federal — é uma das ocorrências mais comuns em fiscalização de rodovia. A prova concentra praticamente toda a cobrança na distinção entre porte para **uso pessoal** (não é crime privativo de liberdade) e **tráfico** (crime grave, hediondo equiparado), critério que a própria lei detalha.

## Teoria essencial

O **porte de drogas para consumo pessoal** (art. 28 da Lei nº 11.343/2006) não é punido com pena privativa de liberdade — as sanções previstas são **advertência sobre os efeitos das drogas**, **prestação de serviços à comunidade** e **medida educativa de comparecimento a programa ou curso educativo**, aplicadas de forma alternativa ou cumulativa, sem gerar antecedente criminal para fins de reincidência penal comum.

O **tráfico de drogas** (art. 33, caput) tipifica um extenso rol de condutas (importar, exportar, remeter, preparar, produzir, fabricar, adquirir, vender, expor à venda, oferecer, ter em depósito, transportar, trazer consigo, guardar, prescrever, ministrar, entregar a consumo ou fornecer drogas, ainda que gratuitamente, sem autorização ou em desacordo com determinação legal ou regulamentar), com pena de reclusão de 5 a 15 anos e multa.

O critério para distinguir usuário de traficante (art. 28, §2º) não é fixado por quantidade mínima objetiva definida em tabela — a lei determina que o juiz, à vista da **natureza e quantidade** da substância apreendida, do **local e das condições** em que se desenvolveu a ação, das **circunstâncias sociais e pessoais**, bem como da **conduta e dos antecedentes** do agente, avalie se a droga se destinava a consumo pessoal ou a tráfico. Essa ausência de critério quantitativo fixo é frequentemente cobrada, pois muitos candidatos assumem, erroneamente, que existe uma quantidade máxima legal definida para uso pessoal.

O **tráfico privilegiado** (art. 33, §4º) reduz a pena de um sexto a dois terços quando o agente for **primário**, de **bons antecedentes**, **não se dedicar às atividades criminosas** nem integrar organização criminosa — presentes cumulativamente esses requisitos. Importante: o STF e o STJ consolidaram entendimento de que o tráfico privilegiado **não é crime equiparado a hediondo** para todos os efeitos, distinguindo-se do tráfico comum quanto a determinados benefícios processuais e execução da pena (embora a matéria tenha tido evolução jurisprudencial relevante, sendo um ponto de atenção redobrada para provas mais recentes).

O tráfico de drogas, na forma do caput do art. 33, é classificado como crime **equiparado a hediondo** pela Lei nº 8.072/1990, com consequências como vedação à fiança em determinadas hipóteses, regime inicial mais gravoso e restrições a benefícios de execução penal.

