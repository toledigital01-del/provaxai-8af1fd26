## Pegadinhas e palavras-armadilha

- Posse (art. 12): **dentro** de casa ou local de trabalho, pena de **detenção**.
- Porte (art. 14): **fora** de casa/trabalho (via pública), pena de **reclusão** — mais grave.
- Arma de uso **restrito** (art. 16): pena ainda mais elevada, com causas de aumento específicas (numeração raspada, agente policial/militar).
- Registro (legaliza a posse) ≠ autorização de porte (legaliza o transporte municiado fora de casa) — são exigências administrativas distintas.

## Letra de lei

