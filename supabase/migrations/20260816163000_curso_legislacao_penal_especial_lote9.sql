## Mapa do tópico — o que cai e por quê

Esse tópico funciona quase como um "índice" que conecta vários outros crimes já estudados — homicídio qualificado, latrocínio, tortura, tráfico — todos ganham um regime jurídico mais rígido quando classificados como hediondos ou equiparados. A prova testa tanto o rol de crimes quanto as consequências específicas dessa classificação.

## Teoria essencial

A Lei nº 8.072/1990 lista taxativamente os **crimes hediondos**: entre os mais relevantes para o edital, estão o **homicídio qualificado** (e, desde alteração legislativa, o homicídio simples quando praticado em atividade típica de grupo de extermínio, mesmo que por um só executor), o **latrocínio** (roubo seguido de morte), a **extorsão qualificada pela morte**, o **estupro** e o **estupro de vulnerável**, a **epidemia com resultado morte**, entre outros crimes graves contra a vida, a dignidade sexual e a saúde pública.

Além dos crimes hediondos propriamente ditos, a lei classifica como **equiparados a hediondos**: **tráfico ilícito de entorpecentes**, **tortura** e **terrorismo** — três crimes de natureza distinta dos hediondos "puros", mas que recebem exatamente o mesmo tratamento jurídico mais rigoroso.

As principais **consequências** da classificação como hediondo ou equiparado: são **insuscetíveis de anistia, graça e indulto** (art. 2º, I); é **vedada a fiança** para os crimes hediondos e equiparados consumados (havendo, porém, discussões e alterações legislativas quanto à liberdade provisória em geral, distinta da fiança); o cumprimento da pena inicia-se, em regra, em **regime fechado**, quando a pena aplicada assim o exigir pela dosimetria; e a **progressão de regime** exige o cumprimento de fração mais elevada da pena do que nos crimes comuns — a Lei nº 13.964/2019 (Pacote Anticrime) reformulou essas frações, estabelecendo percentuais diferenciados conforme se trate de réu primário ou reincidente, e conforme o crime hediondo tenha ou não resultado morte, sendo as frações para hediondos sensivelmente mais altas do que os percentuais aplicáveis a crimes comuns.

Um ponto historicamente importante: o STF já declarou **inconstitucional** a vedação absoluta e automática à progressão de regime nos crimes hediondos (regime integralmente fechado sem possibilidade de progressão), reconhecendo o direito à progressão, ainda que exigindo frações mais rigorosas do que nos crimes comuns — não existe mais, portanto, cumprimento obrigatório de pena inteiramente em regime fechado nesses crimes.

## Como a Cebraspe cobra este assunto

O item costuma testar se o candidato sabe diferenciar crimes hediondos (rol do art. 1º) dos equiparados a hediondos (tráfico, tortura, terrorismo — que não estão tecnicamente no mesmo rol, mas recebem o mesmo tratamento), ou testa se ainda existe vedação absoluta à progressão de regime (não existe mais, após decisão do STF).

## Pegadinhas e palavras-armadilha

- Equiparados a hediondos: **tráfico, tortura e terrorismo** — juridicamente distintos do rol "puro" de hediondos, mas com o mesmo tratamento.
- Consequências: sem anistia/graça/indulto, vedada fiança (crimes consumados), progressão de regime com frações mais altas.
- **Não existe mais** vedação absoluta à progressão de regime — o STF declarou essa vedação total inconstitucional.
- Progressão em hediondo exige fração **maior** que em crime comum, mas ainda é **possível**.

## Letra de lei

Base legal: **Lei nº 8.072/1990** (crimes hediondos), com alterações da **Lei nº 13.964/2019** (Pacote Anticrime, frações de progressão de regime).

## Resumo relâmpago para revisão

