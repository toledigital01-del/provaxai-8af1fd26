## Mapa do tópico — o que cai e por quê

Lei de Tortura tem relevância direta pra atuação policial — é justamente o crime que o próprio agente público pode cometer no exercício (indevido) da função, e a prova testa as modalidades específicas de tortura previstas na lei, além do seu regime especial de cumprimento de pena.

## Teoria essencial

A Lei nº 9.455/1997 tipifica, no art. 1º, duas modalidades principais de tortura: a **tortura-prova/tortura-crime** (inciso I, constranger alguém com emprego de violência ou grave ameaça, causando-lhe sofrimento físico ou mental, com o fim de obter informação, declaração ou confissão da vítima ou de terceira pessoa; para provocar ação ou omissão de natureza criminosa; ou em razão de discriminação racial ou religiosa) e a **tortura-castigo** (inciso II, submeter alguém, sob sua guarda, poder ou autoridade, com emprego de violência ou grave ameaça, a intenso sofrimento físico ou mental, como forma de aplicar castigo pessoal ou medida de caráter preventivo).

A pena para essas modalidades é de reclusão de 2 a 8 anos. Se resultar **lesão corporal grave ou gravíssima**, a pena é de reclusão de 4 a 10 anos; se resultar **morte**, a pena é de reclusão de 8 a 16 anos — modalidades qualificadas pelo resultado.

A **tortura por omissão** (§2º) pune o agente que se **omite** em face dessas condutas, quando tinha o dever de evitá-las ou apurá-las, com pena de detenção de 1 a 4 anos, distinta e menos grave que as modalidades ativas — um ponto de atenção: mesmo essa modalidade omissiva integra o crime de tortura, não sendo mera prevaricação ou infração administrativa.

O crime de tortura é classificado como **crime equiparado a hediondo** pela própria Lei nº 9.455/1997 (art. 2º), com as consequências decorrentes dessa equiparação: é **insuscetível de anistia, graça e indulto**, e o cumprimento da pena começa, em regra, em **regime fechado**.

Um efeito específico da condenação por tortura (art. 1º, §5º) é a **perda do cargo, função ou emprego público**, e a **interdição para seu exercício pelo dobro do prazo da pena aplicada** — efeito automático da condenação, aplicável especificamente quando o crime é praticado por agente público.

## Como a Cebraspe cobra este assunto

O item costuma testar se o candidato sabe que a tortura por omissão também é crime de tortura (embora com pena menor), ou testa a consequência específica da perda do cargo público e a interdição pelo dobro do prazo da pena, aplicável ao agente público condenado.

## Pegadinhas e palavras-armadilha

- Tortura por omissão: também é **crime de tortura** (§2º), com pena de detenção (menor que as formas ativas) — não é mera infração administrativa.
- Tortura é crime **equiparado a hediondo** — insuscetível de anistia, graça e indulto.
- Condenação por tortura de agente público: **perda do cargo** + interdição para seu exercício pelo **dobro do prazo** da pena.
- Tortura qualificada por lesão grave/gravíssima ou morte: penas substancialmente mais altas que a forma simples.

## Letra de lei

Base legal: **arts. 1º e 2º da Lei nº 9.455/1997**.

## Resumo relâmpago para revisão

