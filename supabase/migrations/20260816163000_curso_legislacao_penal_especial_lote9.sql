## Pegadinhas e palavras-armadilha

- **Não existe** quantidade fixa em lei para separar uso pessoal de tráfico — o critério é multifatorial (natureza/quantidade da droga, local, circunstâncias, conduta e antecedentes do agente), avaliado pelo juiz.
- Porte para uso pessoal (art. 28): **sem pena privativa de liberdade** — advertência, prestação de serviços, medida educativa.
- Tráfico: crime **equiparado a hediondo**, pena de reclusão de 5 a 15 anos.
- Tráfico privilegiado (§4º): reduz a pena, mas exige **todos** os requisitos cumulativos (primariedade, bons antecedentes, não dedicação à criminalidade, não integrar organização criminosa).

