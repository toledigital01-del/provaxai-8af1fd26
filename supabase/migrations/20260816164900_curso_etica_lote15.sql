## Mapa do tópico — o que cai e por quê

Improbidade administrativa é o tópico mais denso desse bloco final — a lei passou por reforma significativa em 2021 (Lei nº 14.230/2021), que mudou pontos centrais como a exigência de dolo, e a prova cobra tanto a classificação dos atos ímprobos quanto essas mudanças mais recentes.

## Teoria essencial

A Lei nº 8.429/1992 (Lei de Improbidade Administrativa) classifica os **atos de improbidade** em três categorias: os que causam **enriquecimento ilícito** (art. 9º — auferir vantagem patrimonial indevida em razão do exercício de cargo, mandato, função, emprego ou atividade), os que causam **prejuízo ao erário** (art. 10 — ação ou omissão que enseje perda patrimonial, desvio, apropriação, malbaratamento ou dilapidação de bens/haveres públicos) e os que **atentam contra os princípios** da Administração Pública (art. 11 — violação dos deveres de honestidade, imparcialidade, legalidade e lealdade às instituições, sem necessariamente causar dano patrimonial direto).

Uma mudança central trazida pela **Lei nº 14.230/2021** (reforma da lei de improbidade): passou a exigir expressamente o **dolo** (intenção específica de praticar o ato ímprobo, com consciência da ilicitude) para a configuração de qualquer das três modalidades de improbidade — **afastando a modalidade culposa**, que antes era admitida especificamente para os atos que causam prejuízo ao erário (art. 10, na redação original, admitia improbidade culposa; a reforma extinguiu essa possibilidade, exigindo dolo mesmo nesses casos). Esse é o ponto mais cobrado da disciplina em provas recentes, exatamente por representar uma mudança relevante em relação ao regime jurídico anterior.

As **sanções** aplicáveis, que variam conforme a modalidade e a gravidade do ato (art. 12), podem incluir: perda dos bens ou valores acrescidos ilicitamente ao patrimônio; ressarcimento integral do dano, quando houver; perda da função pública; suspensão dos direitos políticos (por prazo determinado, variável conforme a modalidade); pagamento de multa civil; e proibição de contratar com o Poder Público ou receber benefícios/incentivos fiscais ou creditícios, por prazo determinado. A reforma de 2021 também extinguiu a antiga previsão de aplicação **cumulativa e cumulada** de todas as sanções em bloco, passando a exigir maior individualização e proporcionalidade na dosimetria das sanções pelo julgador, à semelhança da lógica de dosimetria penal.

A **ação de improbidade administrativa** tem legitimidade ativa exclusiva do **Ministério Público**, conforme a redação atual da lei após a reforma de 2021, que extinguiu a legitimidade concorrente das pessoas jurídicas interessadas para propor diretamente a ação (embora estas possam figurar como litisconsortes ou requerer a instauração de procedimento investigativo).

