## Mapa do tópico — o que cai e por quê

Conflito de interesses fecha o curso completo do edital — é um tópico mais recente e específico, que regula situações em que o interesse particular do agente público pode colidir com o interesse público que ele deveria zelar, com especial atenção às restrições que perduram mesmo após a saída do cargo.

## Teoria essencial

A Lei nº 12.813/2013 define **conflito de interesses** como a situação gerada pelo confronto entre interesses públicos e privados, que possa comprometer o interesse coletivo ou influenciar de maneira imprópria o desempenho da função pública — aplicável a ocupantes de cargos ou empregos no Poder Executivo Federal, com regras específicas mais rigorosas para autoridades de escalão mais alto.

A lei tipifica situações que configuram conflito de interesses **durante o exercício do cargo**, como: divulgar ou fazer uso de informação privilegiada, obtida em razão das atividades exercidas, em proveito próprio ou de terceiro; exercer atividade que implique a prestação de serviços ou a manutenção de relação de negócio com pessoa física ou jurídica que tenha interesse em decisão do agente público ou de colegiado do qual participe; praticar ato em benefício de interesse de pessoa jurídica de que participe o agente, seu cônjuge, companheiro ou parentes, e que possa ser por ele beneficiada ou influir em seus atos de gestão; atuar, ainda que informalmente, como procurador, consultor, mediador ou representante de qualquer pessoa ou entidade perante órgão ou entidade da Administração Pública com que tenha vínculo funcional.

Um dos pontos mais específicos e cobrados da lei é a **quarentena** — o período de restrição **após** a saída do cargo, durante o qual o ex-agente público permanece impedido de exercer certas atividades relacionadas às suas antigas atribuições. O prazo geral de quarentena previsto na lei é de **6 meses**, contados da data da dispensa, exoneração, destituição, demissão ou aposentadoria, podendo esse prazo ser diferenciado (mais longo) em hipóteses específicas previstas em atos regulamentares para determinados cargos de maior sensibilidade. Durante a quarentena, o ex-agente pode ficar impedido de prestar, direta ou indiretamente, qualquer tipo de serviço a pessoa física ou jurídica com quem tenha mantido relacionamento oficial nos últimos anos de exercício do cargo, quando o objeto da relação for diretamente relacionado à área de competência do cargo ocupado.

A lei também prevê a possibilidade de o agente solicitar, previamente, **autorização** ou manifestação da Comissão de Ética Pública (ou órgão competente equivalente) sobre a existência ou não de conflito de interesses em determinada situação concreta, funcionando como mecanismo preventivo de orientação, e não apenas repressivo.

