## Mapa do tópico — o que cai e por quê

Inquérito policial é o tópico mais próximo da sua futura rotina prática — é o procedimento que a própria PRF conduz para apurar infrações penais de sua competência. A prova testa as características do inquérito e os prazos de conclusão, que variam conforme o investigado esteja preso ou solto.

## Teoria essencial

O **inquérito policial** é procedimento **administrativo**, presidido pela autoridade policial (delegado de polícia), destinado a apurar a materialidade e a autoria de uma infração penal, reunindo elementos de informação que servirão de base para o titular da ação penal (em regra, o Ministério Público) decidir se oferece ou não a denúncia. Suas características centrais: é **inquisitivo** (não há contraditório pleno nem ampla defesa formal durante sua condução, embora o indiciado tenha direitos assegurados, como o de constituir defensor), **sigiloso** (o sigilo pode ser decretado quando necessário à elucidação do fato ou exigido pelo interesse da sociedade, mas não se opõe ao advogado do investigado, que tem direito de acesso aos elementos já documentados, conforme entendimento consolidado, inclusive em Súmula Vinculante do STF), **discricionário** (a autoridade policial tem certa margem na condução das diligências, embora vinculado à legalidade) e **dispensável** (o Ministério Público pode oferecer denúncia com base em outros elementos de convicção, sem necessidade de inquérito policial prévio, caso já disponha de prova suficiente).

O inquérito pode se iniciar de **ofício** (a autoridade policial toma conhecimento do fato e determina a instauração, mediante portaria), mediante **requisição** do Ministério Público ou do juiz, mediante **requerimento** do ofendido (nos crimes de ação penal pública, cabendo recurso ao chefe de polícia em caso de indeferimento) ou por **auto de prisão em flagrante** (quando o próprio flagrante já formaliza o início do procedimento).

Os **prazos de conclusão** do inquérito, na esfera federal (o que se aplica à PRF), são de **10 dias**, se o indiciado estiver **preso** (contados da data da prisão), e **30 dias**, se estiver **solto**, podendo este último prazo ser prorrogado pela autoridade judicial, mediante representação da autoridade policial, quando as diligências não puderem ser concluídas no prazo original.

O inquérito pode ser **arquivado** quando a autoridade policial (ou, mais precisamente, o Ministério Público, a quem cabe requerer o arquivamento ao juiz) entender que não há elementos suficientes para a ação penal — o arquivamento, em regra, não faz coisa julgada material, podendo o inquérito ser desarquivado se surgirem novas provas, exceto quando o fundamento do arquivamento for a atipicidade do fato ou a extinção da punibilidade, hipóteses em que a jurisprudência reconhece efeitos mais próximos da definitividade.

