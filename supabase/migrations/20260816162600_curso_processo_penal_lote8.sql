## Mapa do tópico — o que cai e por quê

Competência define qual juízo (federal ou estadual, de qual local) vai processar e julgar cada crime — e a prova costuma testar principalmente a competência da Justiça Federal, já que é onde tramitam os crimes de interesse direto da União, incluindo boa parte do que a PRF apura.

## Teoria essencial

A **competência** pode ser fixada por critérios diversos: **ratione loci** (local, em regra, o do local da consumação do crime — art. 70 do CPP, o "lugar da infração"), **ratione materiae** (matéria, distribuindo entre Justiça Federal, Estadual, Eleitoral, Militar), e **ratione personae** (em razão da pessoa, como o foro por prerrogativa de função).

A **competência da Justiça Federal** (art. 109, IV, da Constituição) abrange, entre outras hipóteses, os crimes praticados **em detrimento de bens, serviços ou interesse da União**, de suas entidades autárquicas ou empresas públicas federais — é essa hipótese que atrai para a Justiça Federal, por exemplo, crimes de trânsito ocorridos em rodovia federal que envolvam esses interesses específicos, ou crimes praticados contra o patrimônio da União. Também compete à Justiça Federal julgar crimes previstos em tratado ou convenção internacional, quando iniciada a execução no Brasil e o resultado tenha ou devesse ter ocorrido no estrangeiro, ou vice-versa (art. 109, V).

Um ponto de atenção: a simples circunstância de um crime ocorrer em rodovia federal **não** atrai, por si só, a competência da Justiça Federal — é necessário que exista efetiva lesão a bem, serviço ou interesse da União (patrimônio federal, por exemplo), já que a competência da Justiça Estadual é a **residual**, aplicando-se sempre que não configurada hipótese específica de competência federal, militar ou eleitoral.

O **foro por prerrogativa de função** determina que certas autoridades sejam processadas e julgadas por tribunais específicos, em razão do cargo que ocupam (Presidente da República e Ministros de Estado pelo STF, por exemplo), aplicável apenas aos crimes praticados durante o exercício do cargo e relacionados às funções desempenhadas, conforme entendimento consolidado pelo STF que restringiu a extensão anterior mais ampla do instituto.

A **conexão** e a **continência** são causas de **modificação de competência** que determinam a reunião de processos num único juízo, por razões de economia processual e coerência de julgamento: a conexão ocorre quando crimes estão ligados entre si (mesma ocasião, um praticado para facilitar ou ocultar outro, prova de um influenciando o outro); a continência ocorre quando duas ou mais pessoas são acusadas pela mesma infração (concurso de agentes) ou quando se trata de infração cometida nas condições de concurso formal, aberratio ictus ou aberratio criminis.

