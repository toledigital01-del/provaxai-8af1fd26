## Mapa do tópico — o que cai e por quê

Ação penal é o instrumento que leva o caso investigado ao Judiciário — e a distinção entre suas espécies (pública incondicionada, pública condicionada, privada) determina quem tem legitimidade para iniciar o processo e sob quais condições, sendo um dos pontos mais objetivos e decoráveis da disciplina.

## Teoria essencial

A **ação penal pública incondicionada** é a regra geral no sistema brasileiro (art. 100 do Código Penal): promovida exclusivamente pelo **Ministério Público**, mediante denúncia, independentemente de qualquer manifestação de vontade da vítima. É a espécie aplicável sempre que a lei não disser expressamente o contrário.

A **ação penal pública condicionada** também é promovida pelo Ministério Público, mas depende de uma condição de procedibilidade: a **representação do ofendido** (ou de seu representante legal) ou, em casos excepcionais envolvendo interesse da União, a **requisição do Ministro da Justiça**. Sem a representação, o Ministério Público não pode oferecer a denúncia — mas, uma vez apresentada a representação, o MP não fica vinculado a ela, podendo avaliar livremente se denuncia ou não, com base nos elementos disponíveis.

A **ação penal privada** é promovida pelo próprio **ofendido** (ou seu representante legal), mediante **queixa-crime**, nas hipóteses expressamente previstas em lei — o Ministério Público, nesses casos, atua apenas como fiscal da lei (custos legis), não como titular da ação. A ação privada admite institutos que a pública não admite (ou admite de forma diferente), como a **decadência** (perda do direito de queixa/representação se não exercido no prazo de seis meses, contado do conhecimento da autoria, em regra) e a **perempção** (perda do direito de prosseguir com a ação por inércia processual do querelante, nas hipóteses do art. 60 do CPP).

Um instituto importante que conecta ação penal pública e privada é a **ação penal privada subsidiária da pública** (prevista constitucionalmente, art. 5º, LIX): se o Ministério Público não oferecer a denúncia no prazo legal (inércia, não arquivamento fundamentado), o ofendido pode oferecer queixa substitutiva — mas, mesmo nesse caso, o MP pode retomar a ação como parte principal a qualquer momento (repudiando a queixa e oferecendo denúncia substitutiva), aditar a queixa, ou intervir em todos os termos do processo.

A **decadência** é causa de extinção da punibilidade tanto na ação pública condicionada (se o ofendido não representar no prazo) quanto na ação privada (se o ofendido não oferecer queixa no prazo), em ambos os casos, o prazo regra é de **6 meses** a contar do dia em que veio a saber quem é o autor do crime, salvo prazo diverso previsto expressamente em lei.

