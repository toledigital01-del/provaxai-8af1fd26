- HC preventivo: ameaça, concede **salvo-conduto**. HC liberatório: prisão/constrição já em curso.
- HC **não comporta dilação probatória** — só cabe para questões verificáveis de plano, com prova pré-constituída.
- HC protege especificamente a **liberdade de locomoção** — não é instrumento genérico para qualquer ilegalidade sem relação com essa liberdade.

