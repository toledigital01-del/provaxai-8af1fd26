## Mapa do tópico — o que cai e por quê

Prova é o tópico que sustenta toda a condenação ou absolvição no processo penal — a prova cobra tanto princípios gerais (ônus da prova, livre convicção motivada) quanto a disciplina específica de meios de prova como busca e apreensão e interceptação telefônica, ambos de aplicação prática direta na atividade policial.

## Teoria essencial

O **ônus da prova** no processo penal cabe, em regra, a quem alega: a acusação deve provar a existência do fato e a autoria, cabendo à defesa provar fatos que excluam a ilicitude, a culpabilidade ou extingam a punibilidade (excludentes, causas de justificação) — embora vigore o princípio de que, na dúvida, prevalece o **in dubio pro reo**.

O sistema de valoração de prova adotado é o do **livre convencimento motivado** (persuasão racional): o juiz forma sua convicção livremente a partir das provas produzidas nos autos, mas deve **fundamentar** sua decisão, indicando os elementos que embasaram o julgamento — não vigora nem o sistema de prova tarifada (valor fixo pré-definido para cada prova) nem a íntima convicção sem fundamentação (esta última restrita, no ordenamento brasileiro, ao Tribunal do Júri, quanto ao veredito dos jurados).

São **inadmissíveis** as **provas ilícitas** (obtidas com violação a normas constitucionais ou legais, como confissão mediante tortura) e, em regra, as **provas ilícitas por derivação** (a chamada teoria dos "frutos da árvore envenenada" — provas lícitas em si, mas obtidas a partir de informação derivada de uma prova ilícita original), salvo quando demonstrado que a prova derivada seria obtida por uma **fonte independente**, ou que sua descoberta seria **inevitável** por outros meios legítimos já em curso.

A **busca e apreensão** pode ser domiciliar (exige, em regra, mandado judicial, salvo flagrante delito, desastre ou prestação de socorro, ou, durante o dia, por determinação judicial) ou pessoal (a busca pessoal pode ser realizada sem mandado quando houver fundada suspeita de que a pessoa esteja na posse de arma proibida ou de objetos/papéis que constituam corpo de delito).

A **interceptação telefônica** (Lei nº 9.296/1996) depende de **ordem judicial**, para fins de investigação criminal ou instrução processual penal, sendo vedada quando o fato investigado constituir infração punida, no máximo, com pena de detenção — e tem prazo de 15 dias, renovável por igual período, comprovada a indispensabilidade da diligência.

A **cadeia de custódia** é o conjunto de procedimentos de rastreamento e documentação da prova, desde sua coleta até seu uso em juízo, garantindo a integridade e a idoneidade do elemento probatório — a quebra da cadeia de custódia pode comprometer a validade da prova.

