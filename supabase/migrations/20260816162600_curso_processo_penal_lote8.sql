## Mapa do tópico — o que cai e por quê

Esse é o tópico mais operacional pra você — as regras de prisão em flagrante são exatamente o que a PRF aplica no dia a dia de patrulhamento. A prova testa as espécies de flagrante, os requisitos das prisões cautelares e o rol de medidas cautelares alternativas à prisão, criadas justamente para reduzir o uso da prisão preventiva.

## Teoria essencial

O **flagrante** (art. 302 do CPP) tem quatro espécies: **próprio** (o agente está cometendo a infração, ou acaba de cometê-la), **impróprio** (o agente é perseguido, logo após, em situação que faça presumir ser autor da infração) e **presumido** (o agente é encontrado, logo depois, com instrumentos, armas, objetos ou papéis que façam presumir ser autor da infração) — os dois últimos exigem um lapso temporal reduzido em relação ao momento do crime, sob pena de descaracterizar o flagrante.

A **prisão preventiva** (art. 312) exige, cumulativamente, a presença de **fumus comissi delicti** (prova da existência do crime e indício suficiente de autoria) e de **periculum libertatis**, representado por pelo menos um dos fundamentos: garantia da ordem pública, garantia da ordem econômica, conveniência da instrução criminal, ou asseguração da aplicação da lei penal. Não é cabível prisão preventiva quando o juiz reconhecer, pelas circunstâncias do fato, que o agente atuou sob excludente de ilicitude.

A **prisão temporária** (Lei nº 7.960/1989) é cabível apenas durante a fase de **investigação** (inquérito), em hipóteses taxativas (imprescindibilidade para as investigações, ausência de residência fixa ou identificação, ou fundadas razões de autoria/participação em determinados crimes listados na lei, como homicídio doloso, roubo, tráfico), com prazo de **5 dias**, prorrogável por igual período em caso de extrema e comprovada necessidade (30 dias, prorrogável por igual período, em crimes hediondos).

As **medidas cautelares diversas da prisão** (art. 319), introduzidas para reduzir o encarceramento provisório, incluem: comparecimento periódico em juízo, proibição de acesso ou frequência a determinados lugares, proibição de contato com pessoa determinada, proibição de ausentar-se da comarca, recolhimento domiciliar noturno, suspensão do exercício de função pública, internação provisória (inimputáveis), fiança e monitoração eletrônica. A prisão preventiva deve ser decretada apenas quando **não for cabível sua substituição** por alguma dessas medidas cautelares diversas — é medida de **ultima ratio**, cabível somente quando as demais se mostrarem inadequadas ou insuficientes.

A **audiência de custódia** garante que toda pessoa presa, em flagrante ou não, seja apresentada, em até 24 horas, à autoridade judicial, que avaliará a legalidade e a necessidade da manutenção da prisão, podendo relaxá-la (se ilegal), conceder liberdade provisória (com ou sem medida cautelar diversa) ou converter em preventiva.

