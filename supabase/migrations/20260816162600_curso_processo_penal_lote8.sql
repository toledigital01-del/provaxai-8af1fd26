## Mapa do tópico — o que cai e por quê

O habeas corpus já apareceu em Direito Constitucional como remédio constitucional, mas aqui a prova aprofunda no procedimento processual penal específico — quem pode impetrar, o que pode ser discutido dentro dele, e os limites do seu cabimento, que são mais restritos do que muitos candidatos imaginam.

## Teoria essencial

O **habeas corpus** (art. 5º, LXVIII, da Constituição, e arts. 647 a 667 do CPP) é ação constitucional destinada a proteger a **liberdade de locomoção**, sempre que alguém sofrer ou se achar ameaçado de sofrer **violência ou coação** em sua liberdade de ir e vir, por ilegalidade ou abuso de poder — pode ser **preventivo** (quando ainda não há prisão efetivada, mas ameaça concreta, hipótese em que se concede o **salvo-conduto**) ou **liberatório/repressivo** (quando a prisão ou constrição já está em curso).

A **legitimidade ativa** para impetrar habeas corpus é ampla: qualquer pessoa pode fazê-lo, em seu favor ou de terceiro, **independentemente de capacidade postulatória** (não é necessário ser advogado) — característica que diferencia o habeas corpus da maioria das demais ações, que exigem representação por advogado.

As hipóteses de cabimento (art. 648 do CPP) incluem: quando não houver justa causa; quando alguém estiver preso por mais tempo do que determina a lei; quando quem ordenar a coação não tiver competência para tal; quando houver cessado o motivo que autorizou a coação; quando não for alguém admitido a prestar fiança, nos casos em que a lei a autoriza; quando o processo for manifestamente nulo; quando extinta a punibilidade.

Um limite importante e frequentemente testado: o habeas corpus **não é o instrumento adequado** para discussão que exija **dilação probatória** (análise aprofundada de provas, reexame de fatos e provas), sendo cabível apenas para questões que possam ser verificadas de plano, com base em prova pré-constituída (documental) — matérias que dependam de exame aprofundado de mérito, com produção de novas provas, devem ser discutidas pelas vias processuais ordinárias, não pelo habeas corpus.

O habeas corpus **não é cabível** para questões que não envolvam, direta ou indiretamente, ameaça ou lesão à liberdade de locomoção — por isso não é o instrumento adequado, por exemplo, para discutir exclusivamente questões patrimoniais, ou punições disciplinares que não impliquem privação de liberdade (embora a jurisprudência admita HC contra certas punições disciplinares militares que restrinjam liberdade de locomoção, dentro de limites específicos quanto ao mérito administrativo).

