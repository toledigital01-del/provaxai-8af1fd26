## Mapa do tópico — o que cai e por quê

A prova de inglês da Cebraspe segue o mesmo formato de certo/errado sobre um texto-base — geralmente um texto jornalístico ou técnico, muitas vezes relacionado a segurança pública, trânsito ou temas institucionais. O desafio não é fluência plena, é técnica de leitura: reconhecer estrutura, palavras-chave e não se perder tentando traduzir palavra por palavra.

## Teoria essencial

A leitura eficiente para prova de concurso não exige tradução completa e literal do texto — a estratégia mais eficaz é o **skimming** (leitura rápida para captar a ideia geral do texto: do que ele trata, qual sua tese central) seguido do **scanning** (busca direcionada por informações específicas dentro do texto, guiada pelo enunciado de cada item, sem reler tudo).

Assim como em português e espanhol, a Cebraspe testa se o item reflete **fielmente** o que o texto afirma, sem generalizar informação pontual, sem inverter relação de causa e efeito, e sem contrariar negações ou afirmações específicas do texto. **Cognatos** (palavras semelhantes entre inglês e português, como "information", "police", "traffic", "security") facilitam bastante a compreensão geral, mas exigem atenção aos **false friends** (falsos cognatos): **"actually"** não significa "atualmente" (que é "currently" ou "nowadays"), significa **na verdade/de fato**; **"pretend"** não significa "pretender" (que é "intend"), significa **fingir**; **"college"** não significa "colégio" (ensino médio, que é "high school"), significa **faculdade/universidade**; **"push"** não significa "puxar" (que é "pull"), significa **empurrar**; **"parents"** não significa "parentes" (que é "relatives"), significa **pais**; **"exit"** não significa "êxito" (que é "success"), significa **saída**.

