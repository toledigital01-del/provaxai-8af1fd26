## Mapa do tópico — o que cai e por quê

Tempos verbais é o núcleo gramatical mais testado em inglês para concurso — a prova costuma testar se o candidato sabe distinguir o uso específico de cada tempo (especialmente Present Perfect versus Simple Past, a dupla que mais confunde falantes de português), não apenas a conjugação mecânica.

## Teoria essencial

O **Simple Present** expressa hábitos, verdades gerais e fatos permanentes ("The police patrol the highways" — a polícia patrulha as rodovias, como fato geral/rotina), com a marca característica do "-s" na terceira pessoa do singular. O **Present Continuous** (be + verbo-ing) expressa ação em curso no momento da fala, ou planos futuros já decididos ("The officer is checking the documents" — o policial está verificando os documentos, agora).

O **Simple Past** expressa uma ação **concluída** num momento **específico e determinado** do passado ("The accident happened yesterday" — o acidente aconteceu ontem, momento pontual e definido). O **Present Perfect** (have/has + particípio) expressa uma ação passada **sem** momento específico determinado, com relevância ou conexão para o **presente** ("The driver has lost his license" — o motorista perdeu a carteira, ênfase no resultado atual, sem especificar exatamente quando) — essa distinção (momento específico versus indefinido/conectado ao presente) é a mais cobrada de toda a disciplina, e o erro mais comum do falante de português é usar Simple Past onde o inglês exigiria Present Perfect, e vice-versa.

Um marcador que ajuda a diferenciar os dois: expressões de tempo específico e concluído ("yesterday", "last year", "in 2020") pedem **Simple Past**; expressões que não especificam quando, ou que indicam conexão com o presente ("already", "just", "yet", "never", "ever", "since", "for") costumam pedir **Present Perfect**.

O **Future** em inglês se expressa principalmente por duas construções com sentidos distintos: **"will"** (decisão espontânea, previsão, promessa, tomada no momento da fala) e **"going to"** (plano ou intenção já decidida antes do momento da fala, ou previsão baseada em evidência presente) — distinção sutil, mas frequentemente testada.

## Como a Cebraspe cobra este assunto

O item costuma apresentar uma frase e testar se o Simple Past ou o Present Perfect foi empregado corretamente, com base na presença (ou ausência) de um marcador temporal específico no enunciado — a presença de "yesterday" com verbo no Present Perfect, por exemplo, é erro gramatical clássico testado pela banca.

## Pegadinhas e palavras-armadilha

- Simple Past: ação concluída em momento **específico** e determinado ("yesterday", "last year").
- Present Perfect: ação passada **sem** momento específico, ou com conexão relevante ao presente ("already", "just", "never", "since", "for").
- Marcador de tempo específico e concluído com Present Perfect (ex.: "have arrived yesterday") é erro gramatical clássico.
- "Will" (decisão espontânea/promessa) ≠ "going to" (plano já decidido/previsão com evidência presente).

## Letra de lei

Não se aplica letra de lei — o tópico é regido pela gramática normativa da língua inglesa, cobrada no padrão de concursos.

