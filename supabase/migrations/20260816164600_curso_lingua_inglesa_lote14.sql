## Mapa do tópico — o que cai e por quê

Preposições em inglês não seguem uma lógica de tradução direta do português — cada verbo e expressão tem sua própria preposição "fixa", que muitas vezes não corresponde à preposição usada na construção equivalente em português. Já os conectores seguem a mesma lógica de organização argumentativa já vista em português e espanhol.

## Teoria essencial

As preposições de **tempo** mais cobradas: **"at"** (horários específicos: "at 5 pm"; e locais pontuais: "at the checkpoint"), **"in"** (períodos mais longos: meses, anos, estações: "in 2024", "in June"; e espaços delimitados: "in the car"), **"on"** (dias e datas específicas: "on Monday", "on May 5th"; e superfícies: "on the road"). As preposições de **lugar**: **"in"** (dentro de algo), **"on"** (sobre uma superfície), **"at"** (num ponto específico) — a escolha entre elas segue lógica própria do inglês, nem sempre correspondente à intuição de um falante de português.

Verbos seguidos de preposições fixas (**phrasal verbs** e **verb + preposition** combinations) são amplamente cobrados: **"depend on"** (depender de), **"look for"** (procurar), **"look after"** (cuidar de), **"deal with"** (lidar com), **"comply with"** (cumprir, obedecer — muito relevante para textos sobre lei e regulamentação), **"responsible for"** (responsável por), **"according to"** (de acordo com).

Os **conectores** seguem a mesma lógica lógico-argumentativa de português e espanhol: **aditivos** ("and", "also", "in addition", "moreover"), **adversativos** ("but", "however", "nevertheless", "although"), **causais** ("because", "since", "as", "due to"), **consecutivos** ("so", "therefore", "as a result", "thus") e **condicionais** ("if", "unless" — que já carrega negação embutida, equivalente a "se não/a menos que").

Um ponto de atenção especial é **"unless"**: por já incorporar sentido negativo em si mesma ("a menos que"), não deve ser combinada com outra negação na mesma oração condicional, sob risco de duplicar a negação e inverter o sentido pretendido — diferente de estruturas com "if... not", que expressam a mesma ideia de forma explicitamente negativa.

## Como a Cebraspe cobra este assunto

O item costuma testar se o candidato reconhece a preposição fixa correta associada a um verbo específico ("depend on", não "depend of", erro comum de quem traduz literalmente do português "depender de"), ou testa o valor semântico de um conector destacado no texto.

## Pegadinhas e palavras-armadilha

- "Depend **on**" (não "depend of" — erro clássico de tradução literal do português "depender de").
