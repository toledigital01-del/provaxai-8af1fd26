## Mapa do tópico — o que cai e por quê

Vocabulário em inglês, para concurso, não exige decorar milhares de palavras soltas — exige reconhecer **padrões de formação de palavras** (prefixos, sufixos) que permitem deduzir o sentido de termos desconhecidos a partir de sua estrutura, uma habilidade muito mais rentável do que memorização pura.

## Teoria essencial

A **formação de palavras (word formation)** em inglês segue padrões reconhecíveis por afixação. Sufixos que formam **substantivos** a partir de outras classes: **-tion/-sion** (ex.: "information", "decision"), **-ment** (ex.: "government", "enforcement"), **-ness** (ex.: "awareness", de "aware"), **-ity** (ex.: "security", "responsibility"), **-er/-or** (indicando agente/profissão, ex.: "officer", "director"). Sufixos que formam **adjetivos**: **-ful** (cheio de, ex.: "careful", "powerful"), **-less** (sem, ex.: "careless", "harmless" — atenção, pois é praticamente o **oposto** de "-ful"), **-able/-ible** (capacidade, ex.: "reliable", "responsible"), **-ive** (ex.: "effective", "protective").

Prefixos de **negação** são especialmente cobrados, por inverterem completamente o sentido da palavra-base: **un-** (ex.: "unable", "unsafe"), **in-/im-** (ex.: "incorrect", "impossible"), **dis-** (ex.: "disagree", "disorder") — reconhecer esses prefixos é essencial, já que confundir uma palavra negada com sua forma afirmativa inverte totalmente o sentido de uma frase inteira.

Os **cognatos** (palavras semelhantes ao português, com o mesmo sentido, como "police", "traffic", "information", "security", "criminal", "investigation") facilitam enormemente a leitura de textos técnicos e jornalísticos, especialmente os relacionados a segurança pública e trânsito, área temática recorrente nos textos de prova para cargos policiais — mas, como já visto no tópico de leitura, é preciso atenção aos falsos cognatos que rompem esse padrão de semelhança confiável.

O reconhecimento de **substantivos compostos** (compound nouns), formados pela justaposição de duas palavras (como "traffic light" — semáforo, "checkpoint" — posto de controle, "roadblock" — bloqueio de estrada, "law enforcement" — aplicação da lei/policiamento), é particularmente relevante para o vocabulário técnico de segurança pública e trânsito, área temática que costuma aparecer nos textos-base da prova para o cargo de PRF.

