## Mapa do tópico — o que cai e por quê

Esse tópico conecta o Direito Internacional dos Direitos Humanos com o Direito Constitucional brasileiro — a hierarquia normativa dos tratados internacionais incorporados ao ordenamento é o ponto mais técnico e mais cobrado, especialmente após a diferenciação criada pela Emenda Constitucional nº 45/2004.

## Teoria essencial

A Constituição de 1988 estabelece, no art. 5º, §2º, uma **cláusula de abertura material**: os direitos e garantias nela expressos não excluem outros decorrentes do regime e dos princípios por ela adotados, ou dos **tratados internacionais** em que a República Federativa do Brasil seja parte — reconhecendo, assim, que o rol de direitos fundamentais da Constituição não é taxativo, podendo ser complementado por tratados internacionais de direitos humanos.

A Emenda Constitucional nº 45/2004 acrescentou o **§3º ao art. 5º**, criando um rito específico: os tratados e convenções internacionais sobre direitos humanos que forem aprovados, em cada Casa do Congresso Nacional, em **dois turnos**, por **três quintos dos votos** dos respectivos membros, serão equivalentes às **emendas constitucionais**. Antes dessa emenda, e para os tratados de direitos humanos que não seguem esse rito qualificado, o **STF consolidou entendimento** (RE 466.343) de que possuem **status supralegal** — abaixo da Constituição, mas acima da legislação ordinária, podendo tornar inaplicável (sem revogar formalmente) norma infraconstitucional que os contrarie. Já os tratados internacionais que **não versam sobre direitos humanos** têm, em regra, status de **lei ordinária** apenas.

Essa hierarquização em quatro níveis — Constituição, tratados de direitos humanos com rito do §3º (status de emenda), tratados de direitos humanos sem esse rito (status supralegal) e demais tratados/leis ordinárias — é o ponto mais explorado pela Cebraspe, testando se o candidato sabe posicionar corretamente cada categoria na hierarquia normativa.

Um efeito prático relevante dessa hierarquização foi a discussão sobre a **prisão civil do depositário infiel**, prevista no art. 5º, LXVII, da Constituição, mas incompatível com o Pacto de San José da Costa Rica (que só admite prisão civil por dívida em caso de inadimplemento de obrigação alimentícia) — o STF, reconhecendo o status supralegal do Pacto, entendeu que ele tornou **inaplicável** a legislação infraconstitucional que autorizava essa modalidade de prisão civil, consolidando a **Súmula Vinculante nº 25** ("é ilícita a prisão civil de depositário infiel, qualquer que seja a modalidade do depósito").

