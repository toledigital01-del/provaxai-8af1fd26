## Mapa do tópico — o que cai e por quê

A Declaração Universal de 1948 é o documento fundacional de todo o sistema internacional de proteção de direitos humanos — a prova testa tanto o contexto histórico de sua criação quanto sua natureza jurídica (não é tratado no sentido formal, é declaração de princípios), ponto que costuma gerar confusão.

## Teoria essencial

A **Declaração Universal dos Direitos Humanos (DUDH)** foi adotada pela Assembleia Geral das Nações Unidas em **10 de dezembro de 1948**, em Paris, no contexto imediato do pós-Segunda Guerra Mundial, como resposta direta às atrocidades cometidas pelo regime nazista — a criação da própria Organização das Nações Unidas, em 1945, e a elaboração da Declaração fazem parte do mesmo movimento histórico de reconstrução de uma ordem internacional baseada na dignidade humana.

Um ponto central, frequentemente testado: a DUDH, em sua origem, **não tem natureza de tratado internacional** vinculante no sentido formal e clássico (não foi ratificada como tal pelos Estados, mas sim adotada como resolução da Assembleia Geral) — é uma **declaração de princípios**, um documento de recomendação. Ainda assim, parte expressiva da doutrina e da jurisprudência internacional reconhece que diversos de seus dispositivos adquiriram força de **costume internacional** (direito costumeiro), vinculando os Estados por essa via, independentemente da natureza formal originária do documento.

A Declaração estrutura-se em um **preâmbulo** e **30 artigos**, reconhecendo direitos **civis e políticos** (vida, liberdade, segurança pessoal, proibição de tortura e escravidão, igualdade perante a lei, devido processo legal, liberdade de pensamento, consciência e religião, liberdade de expressão e de reunião, direito de participar do governo) e direitos **econômicos, sociais e culturais** (trabalho, educação, saúde, participação na vida cultural da comunidade, seguridade social) — reunindo, num único documento, as duas grandes categorias de direitos que, posteriormente, seriam desdobradas em dois pactos internacionais distintos (1966).

O art. 1º da Declaração — "Todos os seres humanos nascem livres e iguais em dignidade e direitos" — é frequentemente citado como sua síntese principiológica, consagrando a igualdade e a dignidade como fundamento de todo o restante do documento.

