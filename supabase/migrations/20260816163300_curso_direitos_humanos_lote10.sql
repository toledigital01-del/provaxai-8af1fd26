## Mapa do tópico — o que cai e por quê

Esse tópico fecha a disciplina conectando teoria e prática — como os princípios de direitos humanos se traduzem em regras concretas de conduta para o agente policial, especialmente quanto ao uso da força. É um dos blocos mais aplicados de toda a disciplina, com relação direta ao seu dia a dia profissional.

## Teoria essencial

Os **Princípios Básicos sobre o Uso da Força e Armas de Fogo pelos Encarregados da Aplicação da Lei** (ONU, 1990) estabelecem que o uso da força deve observar os critérios de **legalidade**, **necessidade** (só usar força quando estritamente necessário, e apenas na medida exigida pelo cumprimento do dever), **proporcionalidade** (a intensidade da força deve ser proporcional à gravidade da ameaça ou resistência enfrentada) e **moderação** — o uso de armas de fogo, especificamente, deve ser reservado a situações de risco extremo à vida, priorizando meios não letais sempre que possível e razoável diante das circunstâncias.

O **Código de Conduta para os Encarregados da Aplicação da Lei** (ONU, 1979) estabelece deveres gerais dos agentes de segurança pública: cumprir o dever imposto pela lei, servindo à comunidade e protegendo todas as pessoas contra atos ilegais, em consonância com o alto grau de responsabilidade exigido pela profissão; respeitar e proteger a dignidade humana e os direitos humanos de todas as pessoas; usar a força somente quando estritamente necessário e na medida exigida para o cumprimento do dever; manter sigilo sobre questões de caráter confidencial, salvo quando o cumprimento do dever ou a necessidade de justiça exigirem estritamente o contrário; e não infligir, instigar ou tolerar qualquer ato de tortura ou outros tratamentos cruéis, desumanos ou degradantes, sob nenhuma circunstância, incluindo ordem de superior hierárquico ou circunstâncias excepcionais como estado de guerra ou instabilidade política.

As **Regras de Mandela** (Regras Mínimas das Nações Unidas para o Tratamento de Reclusos, revisadas em 2015) estabelecem padrões mínimos de tratamento digno a pessoas privadas de liberdade, vedando expressamente a tortura e tratamentos cruéis, e regulando condições de confinamento, especialmente restringindo o uso do isolamento solitário prolongado.

A **cidadania**, no contexto constitucional brasileiro, ultrapassa a mera titularidade de direitos políticos (votar e ser votado), englobando a participação ativa na vida pública e social — os instrumentos de **participação social** incluem mecanismos como audiências e consultas públicas, conselhos de participação social, iniciativa popular de lei, plebiscito e referendo, todos voltados a viabilizar o controle social sobre a atuação do Estado, incluindo a atividade policial, reforçando a legitimidade democrática da segurança pública.

