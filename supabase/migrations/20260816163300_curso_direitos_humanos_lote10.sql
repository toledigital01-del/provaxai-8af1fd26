## Mapa do tópico — o que cai e por quê

Depois da Declaração Universal, o sistema internacional de direitos humanos se desdobrou numa série de tratados específicos — a prova testa principalmente os dois grandes pactos de 1966 e o sistema interamericano, especialmente o Pacto de San José da Costa Rica, de aplicação direta na jurisprudência brasileira.

## Teoria essencial

Em **1966**, a ONU adotou dois **pactos internacionais** que desdobraram e deram força jurídica vinculante formal ao conteúdo da Declaração Universal: o **Pacto Internacional sobre Direitos Civis e Políticos (PIDCP)** e o **Pacto Internacional sobre Direitos Econômicos, Sociais e Culturais (PIDESC)** — diferente da Declaração, esses pactos **são tratados internacionais formais**, exigindo ratificação dos Estados para vinculá-los juridicamente. O Brasil ratificou ambos em 1992.

No âmbito regional, o **Sistema Interamericano de Direitos Humanos** tem como documento central a **Convenção Americana sobre Direitos Humanos** (1969), conhecida como **Pacto de San José da Costa Rica**, ratificada pelo Brasil em 1992. A Convenção estabelece dois órgãos de proteção: a **Comissão Interamericana de Direitos Humanos** (que recebe petições e denúncias, podendo emitir recomendações) e a **Corte Interamericana de Direitos Humanos** (órgão jurisdicional, cujas decisões têm caráter vinculante para os Estados que reconheceram sua competência contenciosa, como o Brasil).

Outras convenções específicas frequentemente cobradas: a **Convenção contra a Tortura e Outros Tratamentos ou Penas Cruéis, Desumanos ou Degradantes** (ONU, 1984, ratificada pelo Brasil em 1989); a **Convenção Internacional sobre a Eliminação de Todas as Formas de Discriminação Racial** (1965); a **Convenção sobre os Direitos da Criança** (1989); e a **Convenção sobre os Direitos das Pessoas com Deficiência** (2007), que tem uma particularidade constitucional relevante: foi a **primeira e, por muito tempo, única** convenção internacional de direitos humanos incorporada ao ordenamento brasileiro com **status de emenda constitucional**, por ter sido aprovada pelo rito qualificado do art. 5º, §3º, da Constituição (aprovação em cada Casa do Congresso, em dois turnos, por três quintos dos votos, mesmo procedimento das emendas constitucionais).

O **Código de Conduta para os Encarregados da Aplicação da Lei** e os **Princípios Básicos sobre o Uso da Força e Armas de Fogo pelos Encarregados da Aplicação da Lei**, ambos da ONU, têm relevância direta e específica para a atividade policial, estabelecendo diretrizes internacionais sobre proporcionalidade, necessidade e respeito à dignidade humana no uso da força por agentes de segurança pública.

